// Emits the iPhone charge banner's patterns from the Android source.
//
// InstantAlert.kt is the reviewed, corpus-tested preview reader. The iPhone
// banner must say exactly what the Android one says for the same message, so
// it compiles these same pattern strings instead of a hand-kept copy. The
// extraction is kotlin-source.js, which instant-alert.test.js and
// kotlin-regex.test.js already trust.
//
// Usage: node scripts/generate-ios-instant-alert.mjs [output.swift]
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { constant, patternSource } = require('./test/kotlin-source.js');

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_OUTPUT = path.join(
  ROOT, 'modules/wafra-live-capture/ios/WafraInstantAlertPatterns.generated.swift',
);

const PATTERNS = [
  'UNSAFE_TRANSACTION_RE', 'PURCHASE_PREFIX_RE', 'PROMO_FOOTER_RE', 'REFUSE_RE',
  'CREDIT_RE', 'DEBIT_RE', 'AMOUNT_RE', 'LAST4_RE', 'MERCHANT_RE',
  'PAYMENT_MERCHANT_RE', 'BANK_WORD_RE',
];

const camel = (name) => name.toLowerCase().replace(/_re$/, '')
  .replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());

/** A Swift raw string literal whose delimiter cannot occur inside the value. */
function rawLiteral(value) {
  let hashes = '#';
  // Both `"#` (closes the literal) and `\#` (an escape in a #-raw string).
  while (value.includes(`"${hashes}`) || value.includes(`\\${hashes}`)) hashes += '#';
  return `${hashes}"${value}"${hashes}`;
}

export function instantAlertPatternSources() {
  // `constant` returns the literal as written in the .kt file. Kotlin
  // unescapes a `const val` before it is spliced into a Regex, so "د\\.إ"
  // in source is the pattern د\.إ (a literal dot). Undo that one level here.
  const unescape = (value) => value.replace(/\\\\/g, '\\');
  const CUR_AR = unescape(constant('InstantAlert', 'CUR_AR'));
  const CUR = unescape(constant('InstantAlert', 'CUR', { CUR_AR: constant('InstantAlert', 'CUR_AR') }));
  const sources = Object.fromEntries(PATTERNS.map((name) => [
    camel(name), patternSource('InstantAlert', name, { CUR, CUR_AR }),
  ]));
  sources.credential = patternSource('SensitiveMessageFilter', 'CREDENTIAL_RE');
  return sources;
}

export function swiftSource(sources = instantAlertPatternSources()) {
  const lines = Object.entries(sources).map(([name, value]) =>
    `  static let ${name} = ${rawLiteral(value)}`);
  return '// Generated by scripts/generate-ios-instant-alert.mjs from InstantAlert.kt\n' +
    '// and SensitiveMessageFilter.kt. Do not edit; change the Kotlin and regenerate.\n' +
    'import Foundation\n\n' +
    'enum WafraInstantAlertPatterns {\n' +
    `${lines.join('\n')}\n` +
    '}\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const output = process.argv[2] ?? DEFAULT_OUTPUT;
  fs.writeFileSync(output, swiftSource());
}
