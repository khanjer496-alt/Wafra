'use strict';
/**
 * Package a trained tagger for release and pin it in the app.
 *
 *   node scripts/parser-ai/probe/write-manifest.cjs <workDir> <releaseDir> <version>
 *
 * Copies tagger2.int8.onnx → <releaseDir>/tagger.int8.onnx plus the pruned
 * tokenizer files, computes exact byte sizes and SHA-256, and rewrites
 * src/lib/ai-alert-model-manifest.ts. The release directory is what gets
 * uploaded to the hosting location (NOT done by this script); weights are
 * never committed.
 */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const [work, release, version] = process.argv.slice(2);
if (!work || !release || !version) throw new Error('usage: write-manifest.cjs <workDir> <releaseDir> <version>');
fs.mkdirSync(release, { recursive: true });
const m = JSON.parse(fs.readFileSync(path.join(work, 'tagger2.manifest.json'), 'utf8'));
const files = [
  ['tagger.int8.onnx', path.join(work, 'tagger2.int8.onnx')],
  ['tokenizer.json', path.join(work, 'e5-pruned', 'tokenizer.json')],
  ['tokenizer_config.json', path.join(work, 'e5-pruned', 'tokenizer_config.json')],
];
const artifacts = files.map(([name, src]) => {
  fs.copyFileSync(src, path.join(release, name));
  const buf = fs.readFileSync(path.join(release, name));
  return { name, bytes: buf.length, sha256: crypto.createHash('sha256').update(buf).digest('hex') };
});
const tok = JSON.parse(fs.readFileSync(path.join(work, 'e5-pruned', 'tokenizer.json'), 'utf8'));
const idOf = (piece) => {
  const added = tok.added_tokens.find((t) => t.content === piece);
  if (added) return added.id;
  const i = tok.model.vocab.findIndex(([p]) => p === piece);
  if (i < 0) throw new Error(`piece ${piece}`);
  return i;
};
const labels = {
  tags: m.tags, statuses: m.statuses, families: m.families, directions: m.directions,
  maxTokens: m.maxTokens, clsId: idOf('<s>'), sepId: idOf('</s>'), unkId: idOf('<unk>'),
};
const ts = `/**
 * Pinned artifacts of the on-device alert tagger. GENERATED by
 * scripts/parser-ai/probe/write-manifest.cjs — do not edit by hand.
 *
 * The files are NOT in the repository or the app binary. They are hosted at
 * defaultBaseUrl (a GitHub release of this repository, tag below) and
 * downloaded only when the person asks, then verified by exact size and
 * SHA-256 before use. Encoder: intfloat/multilingual-e5-small (MIT),
 * vocabulary-pruned, fine-tuned on synthetic alerts only, dynamic int8.
 */
export type AiAlertNetworkType = 'wifi' | 'cellular' | 'none' | 'unknown';

export interface AiAlertModelStatus {
  state: 'not-downloaded' | 'downloading' | 'downloaded' | 'ready' | 'failed';
  version: string;
  downloadBytes: number;
  error: string | null;
}

/** Hard ceiling for the whole download, whatever a manifest says. */
export const MAX_TOTAL_BYTES = 45_000_000;

export const AI_ALERT_MODEL_MANIFEST = Object.freeze({
  version: ${JSON.stringify(version)},
  defaultBaseUrl: ${JSON.stringify(`https://github.com/khanjer496-alt/Wafra/releases/download/${version}`)},
  artifacts: ${JSON.stringify(artifacts, null, 2).replace(/\n/g, '\n  ')} as const,
  temperatures: ${JSON.stringify(m.temperatures)} as Record<'tags' | 'status' | 'family' | 'direction' | 'qtags' | 'intent', number>,
  labels: ${JSON.stringify(labels)} as {
    tags: string[];
    statuses: import('@/lib/ai-alert-extractor').AiAlertStatus[];
    families: import('@/lib/ai-alert-extractor').AiAlertFamily[];
    directions: ('debit' | 'credit' | 'none')[];
    maxTokens: number; clsId: number; sepId: number; unkId: number;
  },
  askLabels: ${JSON.stringify({ qtags: m.qtags, intents: m.intents })},
});
`;
fs.writeFileSync(path.resolve(__dirname, '../../../src/lib/ai-alert-model-manifest.ts'), ts);
console.log(JSON.stringify({ version, artifacts, total: artifacts.reduce((s, a) => s + a.bytes, 0) }));
