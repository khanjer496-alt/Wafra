import fs from 'node:fs';
import path from 'node:path';

const CONTROL_OR_BIDI = /[\u0000-\u001f\u007f-\u009f\u061c\u200b-\u200f\u202a-\u202e\u2066-\u2069\ufeff]/u;
const ALIAS_FIELDS = ['alias', 'market', 'bankId', 'evidence'];

function normalizeIosBankSender(value) {
  if (typeof value !== 'string' || value.length === 0 || value.length > 80) return null;
  if (CONTROL_OR_BIDI.test(value)) return null;
  const normalized = value.normalize('NFKC').toLocaleLowerCase('en-US').replace(/[ ._-]/g, '');
  return normalized.length === 0 || normalized.length > 80 ? null : normalized;
}

function invalid(message) {
  throw new Error(`ios-bank-senders: ${message}`);
}

function isPlainObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function isWellFormedUnicode(value) {
  for (let index = 0; index < value.length; index += 1) {
    const unit = value.charCodeAt(index);
    if (unit >= 0xD800 && unit <= 0xDBFF) {
      const next = value.charCodeAt(index + 1);
      if (!(next >= 0xDC00 && next <= 0xDFFF)) return false;
      index += 1;
    } else if (unit >= 0xDC00 && unit <= 0xDFFF) {
      return false;
    }
  }
  return true;
}

function validateRegistry(value) {
  if (!isPlainObject(value) || Object.keys(value).length !== 2 ||
      !Object.hasOwn(value, 'v') || !Object.hasOwn(value, 'aliases') ||
      value.v !== 1 || !Array.isArray(value.aliases)) {
    invalid('registry must be exactly { v: 1, aliases: [] }');
  }

  const aliases = value.aliases.map((entry, index) => {
    if (!isPlainObject(entry) || Object.keys(entry).length !== ALIAS_FIELDS.length ||
        !ALIAS_FIELDS.every((field) => Object.hasOwn(entry, field))) {
      invalid(`alias ${index} must contain only ${ALIAS_FIELDS.join(', ')}`);
    }
    if (typeof entry.alias !== 'string' || !isWellFormedUnicode(entry.alias) ||
        normalizeIosBankSender(entry.alias) === null) {
      invalid(`alias ${index} has an invalid sender label`);
    }
    if (entry.market !== 'AE' && entry.market !== 'SA') invalid(`alias ${index} has an invalid market`);
    if (typeof entry.bankId !== 'string' || !isWellFormedUnicode(entry.bankId) ||
        entry.bankId.length === 0 || entry.bankId.length > 80) {
      invalid(`alias ${index} has an invalid bank ID`);
    }
    if (typeof entry.evidence !== 'string' || !isWellFormedUnicode(entry.evidence) ||
        entry.evidence.trim().length === 0) {
      invalid(`alias ${index} is missing physical-message evidence`);
    }
    return { ...entry, normalized: normalizeIosBankSender(entry.alias) };
  });

  const identities = new Map();
  for (const entry of aliases) {
    const existing = identities.get(entry.normalized);
    if (existing) {
      invalid(`aliases collide after normalization: ${JSON.stringify(entry.alias)}`);
    }
    identities.set(entry.normalized, entry);
  }

  return aliases.sort((left, right) =>
    left.normalized.localeCompare(right.normalized, 'en-US') ||
    left.alias.localeCompare(right.alias, 'en-US'));
}

function swiftStringLiteral(value) {
  const escaped = [...value].map((scalar) => {
    if (scalar === '\\') return '\\\\';
    if (scalar === '"') return '\\"';
    const codePoint = scalar.codePointAt(0);
    if (codePoint <= 0x1F || codePoint === 0x7F || codePoint === 0x2028 || codePoint === 0x2029) {
      return `\\u{${codePoint.toString(16).toUpperCase()}}`;
    }
    return scalar;
  }).join('');
  return `"${escaped}"`;
}

function typeScriptSource(aliases) {
  const rows = aliases.map(({ alias, market, bankId, evidence }) =>
    `  { alias: ${JSON.stringify(alias)}, market: ${JSON.stringify(market)}, bankId: ${JSON.stringify(bankId)}, evidence: ${JSON.stringify(evidence)} },`,
  );
  return `// Generated by scripts/generate-ios-bank-senders.mjs. Do not edit.\n\n` +
    `export const IOS_BANK_SENDER_ALIASES: {\n` +
    `  alias: string;\n  market: 'AE' | 'SA';\n  bankId: string;\n  evidence: string;\n}[] = [\n` +
    `${rows.join('\n')}\n];\n`;
}

function swiftSource(aliases) {
  const rows = aliases.map(({ alias, market, bankId }) =>
    `    ${swiftStringLiteral(normalizeIosBankSender(alias))}: WafraBankSenderIdentity(market: ${swiftStringLiteral(market)}, bankId: ${swiftStringLiteral(bankId)}),`,
  );
  const dictionary = rows.length === 0 ? '[:]' : `[\n${rows.join('\n')}\n  ]`;
  return `// Generated by scripts/generate-ios-bank-senders.mjs. Do not edit.\nimport Foundation\n\n` +
    `public struct WafraBankSenderIdentity: Equatable {\n` +
    `  public let market: String\n  public let bankId: String\n\n` +
    `  public init(market: String, bankId: String) {\n` +
    `    self.market = market\n    self.bankId = bankId\n  }\n}\n\n` +
    `public enum WafraBankSenderRegistry {\n` +
    `  private static let aliases: [String: WafraBankSenderIdentity] = ${dictionary}\n\n` +
    `  private static func isForbidden(_ scalar: Unicode.Scalar) -> Bool {\n` +
    `    switch scalar.value {\n` +
    `    case 0x0000...0x001F, 0x007F...0x009F, 0x061C, 0x200B...0x200F,\n` +
    `         0x202A...0x202E, 0x2066...0x2069, 0xFEFF:\n` +
    `      return true\n` +
    `    default:\n` +
    `      return false\n` +
    `    }\n` +
    `  }\n\n` +
    `  private static func isSeparator(_ scalar: Unicode.Scalar) -> Bool {\n` +
    `    switch scalar.value {\n` +
    `    case 0x20, 0x2E, 0x5F, 0x2D:\n` +
    `      return true\n` +
    `    default:\n` +
    `      return false\n` +
    `    }\n` +
    `  }\n\n` +
    `  public static func normalize(_ value: String) -> String? {\n` +
    `    guard !value.isEmpty, value.utf16.count <= 80 else { return nil }\n` +
    `    guard !value.unicodeScalars.contains(where: isForbidden) else { return nil }\n` +
    `    let source = value.precomposedStringWithCompatibilityMapping\n` +
    `      .lowercased(with: Locale(identifier: "en_US"))\n` +
    `    var normalizedScalars = String.UnicodeScalarView()\n` +
    `    for scalar in source.unicodeScalars where !isSeparator(scalar) {\n` +
    `      normalizedScalars.append(scalar)\n` +
    `    }\n` +
    `    let normalized = String(normalizedScalars)\n` +
    `    guard !normalized.isEmpty, normalized.utf16.count <= 80 else { return nil }\n` +
    `    return normalized\n` +
    `  }\n\n` +
    `  public static func identity(for value: String) -> WafraBankSenderIdentity? {\n` +
    `    guard let key = normalize(value) else { return nil }\n` +
    `    return aliases[key]\n` +
    `  }\n}\n`;
}

const [input, typeScriptOutput, swiftOutput] = process.argv.slice(2);
if (!input || !typeScriptOutput || !swiftOutput || process.argv.length !== 5) {
  console.error('Usage: node scripts/generate-ios-bank-senders.mjs <input.json> <output.ts> <output.swift>');
  process.exit(1);
}

try {
  const registry = JSON.parse(fs.readFileSync(input, 'utf8'));
  const aliases = validateRegistry(registry);
  fs.mkdirSync(path.dirname(typeScriptOutput), { recursive: true });
  fs.mkdirSync(path.dirname(swiftOutput), { recursive: true });
  fs.writeFileSync(typeScriptOutput, typeScriptSource(aliases));
  fs.writeFileSync(swiftOutput, swiftSource(aliases));
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
}
