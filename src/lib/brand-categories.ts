export interface BrandMatch {
  /** The table key the pattern came from (GLOBAL or an ISO country). */
  table: string;
  pattern: string;
  category: CategoryId;
}

interface CompiledBrand extends BrandMatch {
  regex: RegExp;
  gate: string | null;
}

const SEPARATOR = "[\\s./&+,-]*";

function compilePattern(body: string): RegExp {
  const source = body.replace(/ /g, SEPARATOR);
  // A trailing store number is fine (TESCO3345) unless the brand itself ends
  // in a digit, where it would turn A101 into a prefix of A1012.
  const tail = /\d$/.test(body) ? '(?![A-Z0-9])' : '(?![A-Z])';
  return new RegExp(`(?<![A-Z0-9])(?:${source})${tail}`, 'u');
}

let compiled: CompiledBrand[] | null = null;
let index: { byKey: Map<string, CompiledBrand[]>; always: CompiledBrand[] } | null = null;

/**
 * The literal characters every match of `pattern` must start with: two when
 * the pattern opens with two plain characters, one when only the first is
 * plain, none (always test) for a leading group, class, escape or top-level
 * alternation. This is only a prefilter; the regex still decides.
 */
function literalKey(pattern: string): string | null {
  let depth = 0;
  for (const ch of pattern) {
    if (ch === '(') depth++;
    else if (ch === ')') depth--;
    else if (ch === '|' && depth === 0) return null;
  }
  const plain = (i: number) => /[A-Z0-9]/.test(pattern[i] ?? '') && !/[?*{]/.test(pattern[i + 1] ?? '');
  if (!plain(0)) return null;
  return plain(1) ? pattern.slice(0, 2) : pattern[0];
}

function brandIndex(): NonNullable<typeof index> {
  if (index) return index;
  const byKey = new Map<string, CompiledBrand[]>();
  const always: CompiledBrand[] = [];
  for (const brand of compileBrandTable()) {
    const key = literalKey(brand.pattern);
    if (!key) { always.push(brand); continue; }
    const list = byKey.get(key);
    if (list) list.push(brand); else byKey.set(key, [brand]);
  }
  index = { byKey, always };
  return index;
}

/** Parse the table. Throws on an unknown category alias so a typo cannot ship silently. */
export function compileBrandTable(): CompiledBrand[] {
  if (compiled) return compiled;
  const out: CompiledBrand[] = [];
  for (const [table, block] of Object.entries(TABLE)) {
    for (const rawLine of block.split('\n')) {
      const line = rawLine.trim();
      if (!line) continue;
      const colon = line.indexOf(':');
      const alias = line.slice(0, colon).trim();
      const category = ALIAS[alias];
      if (colon < 1 || !category) throw new Error(`brand-categories: bad alias "${alias}" in ${table}`);
      for (const rawPattern of line.slice(colon + 1).split(';')) {
        let pattern = rawPattern.trim();
        if (!pattern) continue;
        const gated = pattern.startsWith('!');
        if (gated) pattern = pattern.slice(1).trim();
        if (gated && table === 'GLOBAL') throw new Error(`brand-categories: GLOBAL pattern cannot be gated: ${pattern}`);
        out.push({ table, pattern, category, regex: compilePattern(pattern), gate: gated ? table : null });
      }
    }
  }
  compiled = out;
  return out;
}

/** Upper-case, accent-free, processor-delimiter-free text the patterns read. */
export function normalizeBrandDescriptor(descriptor: string): string {
  return descriptor
    .normalize('NFKD')
    .replace(/[̀-ͯ]/gu, '')
    .toUpperCase()
    .replace(/['’`]/gu, '')
    .replace(/[*_#|~]+/gu, ' ')
    .replace(/\s+/gu, ' ')
    .trim();
}

/**
 * The category a well-known brand in the descriptor implies, or null.
 * `market` is an ISO country; gated (ambiguous) brands need it to match.
 */
export function matchBrandCategory(descriptor: string, market?: string | null): BrandMatch | null {
  if (typeof descriptor !== 'string' || !descriptor.trim() || descriptor.length > 256) return null;
  const text = normalizeBrandDescriptor(descriptor);
  if (!text) return null;
  const country = typeof market === 'string' ? market.trim().toUpperCase() : null;
  const hits: { brand: CompiledBrand; start: number; end: number }[] = [];
  const { byKey, always } = brandIndex();
  const candidates = new Set<CompiledBrand>(always);
  for (let i = 0; i < text.length; i++) {
    if (!/[A-Z0-9]/.test(text[i]) || (i > 0 && /[A-Z0-9]/.test(text[i - 1]))) continue;
    for (const key of [text[i], text.slice(i, i + 2)]) for (const brand of byKey.get(key) ?? []) candidates.add(brand);
  }
  for (const brand of candidates) {
    if (brand.gate && brand.gate !== country) continue;
    const m = brand.regex.exec(text);
    if (m) hits.push({ brand, start: m.index, end: m.index + m[0].length });
  }
  if (!hits.length) return null;
  let best = hits[0];
  for (const hit of hits) if (hit.end - hit.start > best.end - best.start) best = hit;
  // Conflicting evidence outside the winning span means two different brands
  // (or a brand and a transit word) are present: decline rather than guess.
  for (const hit of hits) {
    if (hit.brand.category === best.brand.category) continue;
    const inside = hit.start >= best.start && hit.end <= best.end;
    if (!inside || hit.end - hit.start === best.end - best.start) return null;
  }
  const { table, pattern, category } = best.brand;
  return { table, pattern, category };
}

/** Size of the table, for tests and evaluation reports. */
export function brandTableStats(): { patterns: number; tables: number; countries: string[]; gated: number } {
  const all = compileBrandTable();
  const countries = Object.keys(TABLE).filter((key) => key !== 'GLOBAL');
  return { patterns: all.length, tables: Object.keys(TABLE).length, countries, gated: all.filter((b) => b.gate).length };
}
