/**
 * Curated consumer-brand table: merchant descriptor -> category.
 *
 * A LAST-RESORT fallback for markets outside the launch-tested AE/SA
 * vocabulary. universal-categorization.ts consults it only after the user's
 * own merchant rules, activity words and the existing merchant vocabulary have
 * all failed to resolve a category, and never for AE/SA.
 *
 * Written from public knowledge of what each chain sells. It was NOT fitted to
 * the phase-1 evaluation descriptors (scripts/parser-ai/category/merchants.cjs).
 *
 * Data format, one block per country (GLOBAL applies everywhere):
 *   `<alias>: PATTERN; PATTERN; ...`
 * - A PATTERN is an uppercase regex fragment matched against a normalised
 *   descriptor (accents stripped, apostrophes removed, `* _ # | ~` -> space).
 *   A space inside a pattern means "zero or more separators" (space . / & + , -),
 *   so `TIM HORTONS` also matches `TIMHORTONS` and `TIM-HORTONS`.
 * - Every pattern is anchored on alphanumeric boundaries. A trailing store
 *   number is allowed (`KROGER0412`) unless the pattern itself ends in a digit.
 * - A leading `!` GATES the pattern to that block's country: it applies only
 *   when the caller's market is that country. Use it for short or ambiguous
 *   tokens (DIA, BIM, D1, ACTION, COOP, TIM, JUMBO, ORANGE, CLARO...).
 * - When several patterns match, the longest wins (UBER EATS over UBER). If a
 *   different-category match lies outside the winner's span, nothing is
 *   returned: `MTA NYCT SUBWAY` is neither a sandwich nor provably a train.
 */

